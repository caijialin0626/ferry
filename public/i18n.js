// Server strings that carry values. Each pattern matches the whole English string.
const zhPatterns = [
  [/^Up to (\d+) images per message\.$/, "每条消息最多附加 $1 张图片。"],
  [/^Codex request timed out: (.+)$/, "Codex 请求超时：$1"],
  [/^(.+) is unreachable right now\.$/, "$1目前不可达。"],
  [/^Default · (.+)$/, "默认 · $1"],
  [/^(\d+) days$/, "$1 天"],
  [/^(\d+) hours$/, "$1 小时"],
  [/^(\d+) minutes$/, "$1 分钟"],
  [/^Fork · (.*)$/, "分叉 · $1"],
  [/^Side · (.*)$/, "侧聊 · $1"],
];

const dictionaries = { zh: { strings: zh, patterns: zhPatterns } };
export const languages = [['en', 'English'], ['zh', '中文']];

function preferredLanguage() {
  try {
    const saved = localStorage.getItem('ferry.lang');
    if (languages.some(([id]) => id === saved)) return saved;
  } catch { /* Storage can be disabled; fall back to the browser language. */ }
  return (navigator.languages?.[0] || navigator.language || 'en').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export const lang = preferredLanguage();
export const locale = lang === 'zh' ? 'zh-CN' : 'en';
const dictionary = dictionaries[lang];

export function setLanguage(value) {
  try {
    if (value) localStorage.setItem('ferry.lang', value);
    else localStorage.removeItem('ferry.lang');
  } catch { /* Keep the current language. */ }
  location.reload();
}

export function savedLanguage() {
  try { return localStorage.getItem('ferry.lang') || ''; } catch { return ''; }
}

export function t(text, params) {
  let value = dictionary?.strings[text] ?? text;
  if (params) value = value.replace(/\{(\w+)\}/g, (match, key) => key in params ? String(params[key]) : match);
  return value;
}

// Translates text that came from an execution machine. Unknown text, such as native agent errors, passes through.
export function translateServer(text) {
  if (typeof text !== 'string' || !dictionary) return text;
  if (Object.hasOwn(dictionary.strings, text)) return dictionary.strings[text];
  for (const [pattern, replacement] of dictionary.patterns) {
    if (pattern.test(text)) return text.replace(pattern, replacement);
  }
  return text;
}

const attributes = ['title', 'aria-label', 'placeholder', 'alt', 'data-select-label'];
// Translates the static markup once at startup. Dynamic UI calls t() directly.
export function translatePage(root = document.body) {
  document.documentElement.lang = locale;
  if (!dictionary) return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  for (let node = walker.nextNode(); node; node = walker.nextNode()) {
    const text = node.nodeValue.trim();
    if (text && Object.hasOwn(dictionary.strings, text)) node.nodeValue = node.nodeValue.replace(text, dictionary.strings[text]);
  }
  for (const element of root.querySelectorAll('*')) {
    for (const name of attributes) {
      const value = element.getAttribute(name);
      if (value && Object.hasOwn(dictionary.strings, value)) element.setAttribute(name, dictionary.strings[value]);
    }
    if (element.hasAttribute('data-i18n-html')) {
      const html = element.innerHTML.trim();
      if (Object.hasOwn(dictionary.strings, html)) element.innerHTML = dictionary.strings[html];
    }
  }
}
